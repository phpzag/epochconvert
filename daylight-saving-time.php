    <h2>Frequently Asked Questions (FAQ)</h2>
    <dl>
      <dt>🕓 What is the main purpose of Daylight Saving Time?</dt>
      <dd>The main goal is to make better use of daylight during the longer days of summer by shifting one hour of daylight from the morning to the evening.</dd>

      <dt>🌅 When do we move clocks forward or backward?</dt>
      <dd>Clocks are moved forward by one hour in spring ("spring forward") to start DST and moved backward by one hour in autumn ("fall back") when DST ends.</dd>

      <dt>🌍 Do all countries observe DST?</dt>
      <dd>No. Many countries near the equator do not observe DST because daylight duration changes very little throughout the year. Countries closer to the poles are more likely to use DST.</dd>

      <dt>💡 Does DST really save energy?</dt>
      <dd>Originally, DST was introduced to reduce energy use by extending daylight hours. However, modern studies show mixed results, as energy savings depend on region, climate, and electricity usage patterns.</dd>

      <dt>🔁 Why do some countries stop or change DST rules?</dt>
      <dd>Governments may change or abolish DST based on public opinion, health studies, or economic factors. For example, some regions have stopped DST due to minimal energy savings or health concerns from disrupted sleep schedules.</dd>

      <dt>🗓️ How can I know if my region observes DST?</dt>
      <dd>You can check your country’s official time authority website or consult the <a href="https://en.wikipedia.org/wiki/Daylight_saving_time_by_country" target="_blank">DST by country list on Wikipedia</a>.</dd>
