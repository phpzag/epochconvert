    <p><strong>Daylight Saving Time (DST)</strong> is the practice of setting the clock forward by one hour during the warmer months of the year to extend evening daylight. The goal is to make better use of natural daylight, conserve energy, and align working hours with daylight hours.</p>
    <p>Typically, clocks are set forward in spring (<em>"spring forward"</em>) and set back in autumn (<em>"fall back"</em>). Not all countries observe DST — and even among those that do, the start and end dates can vary significantly depending on regional laws and latitude.</p>
